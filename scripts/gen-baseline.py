"""Writes crates/coiman-core/data/baseline.tsv from the data.json of the npm package web-features.

Usage: python -I scripts/gen-baseline.py <data.json> <version> crates/coiman-core/data/baseline.tsv

Only CSS and HTML features at the level the editor can see them are kept: a
property, a keyword value of one, a selector, at-rule or function, or an element.
"""

import json
import sys

KEPT = ("css.properties.", "css.selectors.", "css.at-rules.", "html.elements.")


def short_key(key):
    """The key the editor looks up, or None if it is finer than the editor can tell."""
    parts = key.split(".")
    if key.startswith(KEPT) and len(parts) == 3:
        return key
    # A keyword value, such as css.properties.display.grid. Names with `_` are
    # contexts the data adds, not words anyone writes.
    if key.startswith("css.properties.") and len(parts) == 4 and "_" not in parts[3]:
        return key
    # Functions sit under the type they make: css.types.color.oklch.
    if key.startswith("css.types.") and len(parts) in (3, 4):
        return "css.types." + parts[-1]
    return None


def main():
    data_path, version, out_path = sys.argv[1:4]
    with open(data_path, encoding="utf-8") as f:
        features = json.load(f)["features"]
    rows = {}
    for feature in features.values():
        if feature.get("kind") != "feature":
            continue
        for key, status in feature.get("status", {}).get("by_compat_key", {}).items():
            short = short_key(key)
            if short is None or short in rows:
                continue
            level = status.get("baseline")
            rows[short] = (
                level if level in ("high", "low") else "no",
                status.get("baseline_low_date", ""),
                status.get("baseline_high_date", ""),
                feature["name"].replace("\t", " "),
            )
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# Generated by scripts/gen-baseline.py from web-features {version}.\n")
        f.write("# web-features is (c) the W3C WebDX Community Group, Apache-2.0.\n")
        for key in sorted(rows):
            f.write(key + "\t" + "\t".join(rows[key]) + "\n")
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
