/// Commands whose shortcuts still work while the terminal has focus; every
/// other key goes to the shell (like VS Code's `commandsToSkipShell`).
pub fn runs_in_terminal(cmd: Command) -> bool {
    use Command::*;
    matches!(
        cmd,
        CommandPalette
            | QuickOpen
            | SearchEverywhere
            | ToggleTerminal
            | NewTerminal
            | ShowExplorer
            | ShowSearch
            | ShowProblems
            | ShowSourceControl
            | ShowTesting
            | ShowOutput
            | RunWithoutDebugging
            | RunProgram
            | RunCurrentFile
            | ChooseRunTarget
            | OpenLivePreview
            | ShowLanguageDoctor
            | SendToRepl
            | ChoosePython
            | OpenLanguagesFile
            | StopLivePreview
            | ConstantPreview
            | StartDebugging
            | StopDebugging
            | ShowDebug
            | ShowExtensions
            | NextEditor
            | PreviousEditor
            | ZoomIn
            | ZoomOut
            | ResetZoom
            | CodeZoomIn
            | CodeZoomOut
            | ResetCodeZoom
            | ToggleZenMode
            | NextProblem
            | PreviousProblem
    )
}

pub fn command_id(cmd: Command) -> &'static str {
    COMMAND_IDS.iter().find(|(c, _)| *c == cmd).map_or("", |(_, id)| id)
}

pub fn command_from_id(id: &str) -> Option<Command> {
    COMMAND_IDS.iter().find(|(_, i)| *i == id).map(|(c, _)| *c)
}
